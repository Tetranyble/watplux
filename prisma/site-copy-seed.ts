import type { PrismaClient } from "@prisma/client";

type SiteCopySeed = {
  key: string;
  namespace: string;
  label: string;
  value: string;
  description?: string;
  multiline?: boolean;
  sortOrder: number;
};

function group(
  namespace: string,
  entries: Array<
    [key: string, label: string, value: string, multiline?: boolean]
  >,
): SiteCopySeed[] {
  return entries.map(([key, label, value, multiline], index) => ({
    key: `${namespace}.${key}`,
    namespace,
    label,
    value,
    multiline: multiline ?? false,
    sortOrder: index * 10,
  }));
}

