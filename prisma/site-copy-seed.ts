export async function seedSiteCopy(db: PrismaClient): Promise<void> {
  for (const entry of SITE_COPY_SEED) {
    await db.siteCopy.upsert({
      where: { key: entry.key },
      create: entry,
      update: {
        namespace: entry.namespace,
        label: entry.label,
        description: entry.description,
        multiline: entry.multiline,
        sortOrder: entry.sortOrder,
      },
    });
  }
}
